// The collector table.
//
// Each entry is one MARKUP SHAPE, not one provider — AdSense appears as a script query parameter,
// as a data-ad-client attribute, as a meta tag and as a legacy global assignment, and those are
// four collectors because they are four regexes with four different anchors.
//
// Every pattern was measured against a corpus of live documents (177 pages, 96 ads.txt and
// app-ads.txt files, fetched tag-manager containers, /.well-known/ documents) plus a negative
// corpus of 23 pages and four minified libraries. A pattern that fired in the negative corpus was
// anchored harder or dropped. That is why so many look over-specified: the unanchored version of
// the same pattern mines base64. Measured leak rate across all 121 collectors against the minified
// libraries: zero.
//
// THREE COLLECTORS WERE WRITTEN AND THEN DELETED, and the reasons generalise:
//   - Adsterra's pl<digits> serving subdomain. It is a HOST label that rotates weekly, not an
//     account, so every rotation would have minted a second operator node for one operator.
//   - Google Floodlight's DC- advertiser id. The width came from the catalogue and nothing in
//     350+ corpus documents corroborated it. An unverified pattern is not a cheap bet; it is a
//     node nobody can trace back to bytes.
//   - The generic network referral id. It emits bare digits into the same namespace as ExoClick
//     and JuicyAds zone ids, and nothing in the value distinguishes the two.
export type HitPhase = 'markup' | 'adstxt' | 'wellknown' | 'gtm';

export interface Collector {
    /** Unique; appears in the run log so a bad emit can be traced to one rule. */
    key: string;
    /** Namespace slug for the node value. Empty when `providerFromGroup` supplies it per match. */
    provider: string;
    /** ads.txt names its ad system in field 1, so the provider comes out of the match itself. */
    providerFromGroup?: number;
    /** web.tracking_id `kind`. */
    kind: string;
    /** web.tracking_id `source`. */
    source: string;
    phase: HitPhase;
    /** Regex SOURCE. Compiled per document — never store a compiled `g` regex here. */
    regex: string;
    flags: string;
    /** 1-based capture group holding the raw identifier. */
    group: number;
    /** Whole-document precondition; the collector is skipped when it does not match. */
    pageGuard?: string;
    /** Literal raw values that must never become nodes (hubs, demos, placeholders). */
    reject?: string[];
    rejectRegex?: string;
    /**
     * Case-fold the raw value before it becomes a node.
     *
     * Needed wherever a pattern accepts mixed-case hex or an identifier the issuer treats as
     * case-insensitive. Identity is the value string, so `A1B2` and `a1b2` are two nodes for one
     * account — a split that looks like two operators and is invisible on the canvas.
     */
    normalize?: 'lower';
    /** Percent-decode before emitting. Set on the email collectors: `%40` is common in an href. */
    urldecode?: boolean;
    /**
     * Off unless the caller asks for it.
     *
     * One collector carries this: the ads.txt DIRECT sweep. It is not noisy, it is VOLUMINOUS —
     * measured 7,334 nodes from 88 publisher hosts, a median of 74 per file and 1,637 from the
     * largest. Most of those rows are the publisher's relationship with an ad exchange that ten
     * thousand other publishers also use, and ten food blogs sharing one agency's copied ads.txt
     * produced a 10-way clique of 54 shared nodes that no reject list can prevent. The
     * high-value, low-volume rows in the same file — the publisher's own Google account,
     * OWNERDOMAIN, INVENTORYPARTNERDOMAIN — are separate collectors and stay on.
     */
    optIn?: boolean;
    /** 'email' routes to identity.email_address instead of web.tracking_id. */
    emit?: 'tracking_id' | 'email';
    note: string;
}

