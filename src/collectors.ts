/**
 * The other half of the google/adsense merge: ads.txt writes the account as `pub-…` and the
 * AdSense tag writes the same account as `ca-pub-…`. Restore the prefix so the two converge.
 */
export function googlePubPrefix(provider: string, raw: string): string {
    return provider === 'adsense' && raw.startsWith('pub-') ? `ca-${raw}` : raw;
}

